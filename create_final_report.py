
from pathlib import Path
from datetime import date
import pandas as pd

BASE_DIR = Path(__file__).resolve().parent
DATA_DIR = BASE_DIR / "data"
OUTPUT_FILE = DATA_DIR / "SoCo_Final_Project_Report.md"

def load_csv(filename):
    path = DATA_DIR / filename
    if not path.exists():
        print(f"Skipping missing file: {filename}")
        return None
    return pd.read_csv(path)

businesses = load_csv("business_locations.csv")
rankings = load_csv("ranked_corridors.csv")
road_summary = load_csv("cluster_road_summary.csv")
road_matches = load_csv("business_road_matches.csv")
analysis = load_csv("corridor_analysis.csv")

lines = []

def add(text=""):
    lines.append(str(text))

add("# SoCo Corridor Analysis")
add("## South Congress Avenue, Austin, Texas")
add()
add(f"**Report generated:** {date.today().isoformat()}")
add()
add("## 1. Project objective")
add(
    "This project uses OpenStreetMap road and business data to explore "
    "commercial activity around the South Congress area of Austin, Texas. "
    "It groups nearby businesses, compares cluster density and category "
    "diversity, matches businesses to nearby named roads, and visualizes "
    "the resulting commercial patterns."
)
add()
add("## 2. Data and tools")
add("- Business locations and categories from the existing project dataset.")
add("- Road network geometry and road names from OpenStreetMap-derived data.")
add("- Python, pandas, GeoPandas, Matplotlib, and scikit-learn-based clustering "
    "where used by the existing analysis.")
add("- Existing CSV outputs and map visualizations generated by the project.")
add()
add("## 3. Dataset overview")

if businesses is not None:
    add(f"- Business location records: **{len(businesses)}**")
    if "category" in businesses.columns:
        add("- Most common business categories:")
        for category, count in businesses["category"].value_counts().head(10).items():
            add(f"  - {category}: {count}")
else:
    add("- Business location summary unavailable: input CSV not found.")

add()
add("## 4. Corridor ranking methodology")
add(
    "The existing ranking script combines normalized business density, "
    "business-category diversity, and road proximity using the following "
    "weighted formula:"
)
add()
add("`Corridor Score = 100 × (0.50 × Density + 0.30 × Diversity + 0.20 × Road Score)`")
add()
add(
    "The score is a project-defined comparison metric, not an official "
    "measure of corridor quality. Its ranking depends on the selected "
    "weights, clustering settings, data coverage, and normalization method."
)
add()

if rankings is not None:
    add("### Existing ranked clusters")
    columns = [
        c for c in [
            "rank", "cluster", "business_count", "category_count",
            "corridor_score", "nearest_road_distance_m"
        ] if c in rankings.columns
    ]
    if columns:
        add("| " + " | ".join(columns) + " |")
        add("| " + " | ".join(["---"] * len(columns)) + " |")
        for _, row in rankings.head(10)[columns].iterrows():
            values = []
            for col in columns:
                value = row[col]
                if pd.isna(value):
                    values.append("N/A")
                elif isinstance(value, float):
                    values.append(f"{value:.2f}")
                else:
                    values.append(str(value))
            add("| " + " | ".join(values) + " |")

add()
add("## 5. South Congress Avenue road matching")
add(
    "The road-matching output associates business clusters with nearby "
    "named roads. This helps identify which clusters are most relevant "
    "to South Congress Avenue, instead of assuming the highest-ranked "
    "cluster is automatically the target corridor."
)
add()

if road_summary is not None and {
    "cluster", "nearest_road", "businesses_near_road"
}.issubset(road_summary.columns):
    soco = road_summary[
        road_summary["nearest_road"].astype(str).str.contains(
            "South Congress Avenue", case=False, na=False
        )
    ]
    if not soco.empty:
        add("| Cluster | Businesses matched to South Congress Avenue |")
        add("| --- | ---: |")
        for _, row in soco.iterrows():
            add(f"| {row['cluster']} | {row['businesses_near_road']} |")
    else:
        add(
            "No exact South Congress Avenue matches were found in the "
            "summary output. Check road-name matching before finalizing."
        )
else:
    add("Road summary unavailable or missing expected columns.")

add()
add("## 6. Key findings")
add(
    "- The existing business clustering identifies multiple commercial "
    "groups within the sampled area."
)
add(
    "- Cluster 2 ranks first in the current scoring output, with 39 "
    "businesses and 21 categories; however, many of its matched businesses "
    "are associated with South 1st Street. It should not automatically be "
    "treated as the South Congress Avenue core."
)
add(
    "- Cluster 0 contains 33 businesses, and the existing road summary "
    "matches 16 businesses in that cluster to South Congress Avenue. "
    "It is a useful candidate for further inspection, not a verified boundary."
)
add(
    "- Road matching and business locations should be checked on the map "
    "before declaring which cluster best represents the corridor."
)
add()
add("## 7. Limitations")
add(
    "- The sampled area is based on the project's existing geographic "
    "coverage; it is not necessarily an official South Congress Avenue boundary."
)
add(
    "- OpenStreetMap business names, categories, and road names may be "
    "missing, outdated, or inconsistently tagged."
)
add(
    "- A nearest-road match is a geometric proximity result and does not "
    "prove that a business has a South Congress Avenue address."
)
add(
    "- Cluster IDs are algorithm-generated labels and do not represent "
    "quality or importance by themselves."
)
add(
    "- The ranking formula uses chosen weights. Results may change if the "
    "weights, clustering parameters, or geographic study area change."
)
add()
add("## 8. Recommendations")
add(
    "1. Define the study corridor using a verified geographic boundary "
    "or an explicitly documented street segment."
)
add(
    "2. Filter businesses by their actual proximity to the selected road "
    "or corridor polygon, rather than relying only on cluster membership."
)
add(
    "3. Review missing business names and generic categories to improve "
    "data quality."
)
add(
    "4. Compare business density and category diversity within the "
    "validated corridor."
)
add(
    "5. Keep the scoring formula and its weights visible in presentations "
    "so the ranking is transparent."
)
add()
add("## 9. Project outputs")
add("- `data/business_locations.csv` — collected business records.")
add("- `data/business_clusters.csv` — business records with cluster labels.")
add("- `data/ranked_corridors.csv` — existing cluster rankings.")
add("- `data/business_road_matches.csv` — business-to-road matching results.")
add("- `data/cluster_road_summary.csv` — summary of road matches.")
add("- `data/final_corridor_map.png` — final map visualization.")
add()
add("## 10. Conclusion")
add(
    "This project demonstrates a data-driven workflow for exploring "
    "commercial activity near South Congress Avenue. Its key contribution "
    "is combining business clustering, category diversity, road matching, "
    "and visualization. Final claims about the SoCo corridor should be "
    "made only after confirming the study boundary and validating the "
    "business-to-road associations."
)
add()
add("---")
add("*Prepared from the project's existing output files. Findings depend "
    "on the coverage and quality of those files.*")

OUTPUT_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")

print("\nReport created successfully:")
print(OUTPUT_FILE)
print("\nOpen it in VS Code to review the findings.")
